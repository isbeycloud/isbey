import { test, expect } from './fixtures/adminSession';

test('store device setup persists as draft and does not simulate a successful collection', async ({ page, request, adminSession }) => {
  const { token } = adminSession;
  const headers = { Authorization: `Bearer ${token}` };
  const financialRoutes = ['/api/invoices', '/api/customers', '/api/v1/pos/transactions'];
  const before = await Promise.all(financialRoutes.map(async path => (await request.get(path, { headers })).json()));
  await page.addInitScript(value => localStorage.setItem('isbey_token', value), token);
  await page.goto('/');
  await page.locator('aside').getByText('Hızlı Satış (POS)', { exact: true }).click();
  await page.getByRole('button', { name: 'Yazar Kasa / POS Bağlantıları', exact: true }).click();
  const dialog = page.getByRole('dialog', { name: 'Mağaza Cihaz Bağlantıları' });
  await expect(dialog.getByRole('heading', { name: 'Yazar Kasa / POS Bağlantıları' })).toBeVisible();
  const form = dialog.getByRole('form', { name: 'Cihaz tanımı' });
  await form.getByLabel('Bağlantı kütüphanesi').selectOption('beko-tokenx-wire');
  await form.getByLabel('Cihaz adı', { exact: true }).fill('E2E Beko kasa');
  await form.getByLabel('Model', { exact: true }).fill('300TR');
  await form.getByLabel('Sicil / seri numarası').fill('E2E-BEKO-LOCAL');
  await form.getByLabel('Şube / mağaza').fill('Deneme mağazası');
  await form.getByLabel('Kasa bilgisayarı').fill('KASA-01');
  await form.getByRole('button', { name: 'Cihaz Tanımını Kaydet' }).click();
  await expect(dialog.getByText('Cihaz tanımı taslak olarak kaydedildi.', { exact: false })).toBeVisible();
  const card = dialog.getByRole('article', { name: 'E2E Beko kasa' });
  await card.getByRole('button', { name: 'Kurulum Durumu', exact: true }).click();
  const readiness = dialog.getByRole('region', { name: 'Cihaz kurulum durumu' });
  await expect(readiness.getByText('Bu kontrol cihazla iletişim kurmaz.', { exact: false })).toBeVisible();
  await expect(readiness.getByRole('button', { name: 'Cihazdan Tahsilat — Hazır Değil' })).toBeDisabled();
  await page.screenshot({ path: '.verify-tmp/fiscal-devices-desktop.png', fullPage: true });
  await card.getByRole('button', { name: 'Düzenle', exact: true }).click();
  await form.getByLabel('Cihaz adı', { exact: true }).fill('E2E Beko ikinci kasa');
  await form.getByRole('button', { name: 'Cihaz Tanımını Kaydet' }).click();
  await expect(dialog.getByRole('article', { name: 'E2E Beko ikinci kasa' })).toBeVisible();
  await dialog.getByRole('button', { name: 'Kapat', exact: true }).click();
  await page.reload();
  await page.locator('aside').getByText('Hızlı Satış (POS)', { exact: true }).click();
  await page.getByRole('button', { name: 'Yazar Kasa / POS Bağlantıları', exact: true }).click();
  const saved = dialog.getByRole('article', { name: 'E2E Beko ikinci kasa' });
  await expect(saved).toBeVisible();
  await page.setViewportSize({ width: 390, height: 844 });
  expect(await dialog.evaluate(el => el.scrollWidth <= el.clientWidth + 1)).toBe(true);
  await page.screenshot({ path: '.verify-tmp/fiscal-devices-mobile.png', fullPage: true });
  await saved.getByRole('button', { name: 'Devre Dışı Bırak' }).click();
  await expect(saved.getByText('Devre dışı', { exact: true })).toBeVisible();
  const result = await request.post('/api/v1/pos/charge', { headers, data: { amount: 1, companyId: 'another-company' } });
  expect(result.status()).toBe(503); expect((await result.json()).code).toBe('FISCAL_DEVICE_NOT_READY');
  for (let i = 0; i < financialRoutes.length; i++) expect(await (await request.get(financialRoutes[i], { headers })).json()).toEqual(before[i]);
});
