import { test, expect } from '@playwright/test';

test('platform and company management save free and paid customer packages', async ({ page, request }) => {
  const login = await request.post('/api/auth/login', { data: { username: 'admin', password: 'admin123' } });
  expect(login.status()).toBe(200);
  const { token } = await login.json();
  const headers = { Authorization: `Bearer ${token}` };
  const name = `Paket Yönetimi Test ${Date.now()}`;
  const created = await request.post('/api/companies', { headers, data: {
    name, title: name, taxNumber: '9000000010', email: 'packages@example.test', plan: 'PRO', createAdminUser: false,
  } });
  expect(created.status()).toBe(200);
  const { company } = await created.json();
  const financialBefore = await request.get('/api/invoices', { headers });
  const invoicesBefore = await financialBefore.json();
  await page.addInitScript(value => localStorage.setItem('isbey_token', value), token);
  const errors: string[] = []; page.on('pageerror', e => errors.push(e.message));
  await page.goto('/');
  await page.getByRole('button', { name: /Firmalar \/ Tenants/ }).click();
  const row = page.getByRole('row').filter({ hasText: name });
  await row.getByRole('button', { name: 'Paket / Ücret', exact: true }).click();
  const modal = page.locator('.modal-dialog').filter({ hasText: 'Müşteri Paket Yönetimi' });
  await expect(modal.getByRole('heading', { name: /Paket ve kullanım koşulları/ })).toBeVisible();
  const packages = modal.getByRole('group', { name: 'Hizmet paketleri' }).getByRole('checkbox');
  expect(await packages.count()).toBeGreaterThan(0);
  for (let i = 0; i < await packages.count(); i++) await packages.nth(i).setChecked(i === 0);
  await modal.getByRole('radio', { name: 'Ücretsiz', exact: true }).check();
  await modal.getByLabel('Başlangıç tarihi', { exact: true }).fill('2026-01-01');
  await modal.getByLabel('Bitiş tarihi', { exact: true }).fill('2099-12-31');
  await modal.getByLabel('Değişiklik gerekçesi', { exact: true }).fill('Müşteri için ücretsiz kullanım onaylandı');
  const savedFree = page.waitForResponse(r => r.url().endsWith(`/api/companies/${company.id}/package`) && r.request().method() === 'PUT');
  await modal.getByRole('button', { name: 'Paket Değişikliğini Kaydet' }).click();
  expect((await savedFree).status()).toBe(200);
  await expect(modal.getByLabel('Değişiklik gerekçesi')).toHaveValue('');
  const free = await (await request.get(`/api/companies/${company.id}/package`, { headers })).json();
  expect(free.tenant.commercialSubscription.billingMode).toBe('FREE');
  expect(free.tenant.commercialSubscription.amount).toBe(0);
  await modal.getByRole('radio', { name: 'Ücretli', exact: true }).check();
  await modal.getByLabel('Faturalama dönemi').selectOption('yearly');
  const custom = modal.getByRole('checkbox', { name: 'Anlaşmalı bedel kullan' });
  await custom.check();
  await modal.getByLabel('Anlaşmalı dönem bedeli', { exact: true }).fill('1200');
  await modal.getByLabel('Değişiklik gerekçesi').fill('Yıllık ücretli pakete müşteri talebiyle geçildi');
  const savedPaid = page.waitForResponse(r => r.url().endsWith(`/api/companies/${company.id}/package`) && r.request().method() === 'PUT');
  await modal.getByRole('button', { name: 'Paket Değişikliğini Kaydet' }).click();
  expect((await savedPaid).status()).toBe(200);
  await expect(modal.getByLabel('Değişiklik gerekçesi')).toHaveValue('');
  await modal.locator('.modal-header button').click();
  await expect(row.getByText('Ücretli', { exact: true })).toBeVisible();
  await page.locator('aside').getByText('Firma & Şirketler', { exact: true }).click();
  const companyRow = page.getByRole('row').filter({ hasText: name });
  await expect(companyRow.getByText('Ücretli', { exact: true })).toBeVisible();
  await companyRow.getByRole('button', { name: 'Paket / Ücret', exact: true }).click();
  await expect(modal.getByLabel('Anlaşmalı dönem bedeli', { exact: true })).toHaveValue('1200');
  await modal.getByText('Son paket değişiklikleri (2)', { exact: true }).click();
  await expect(modal.getByText('Yıllık ücretli pakete müşteri talebiyle geçildi', { exact: true })).toBeVisible();
  await page.screenshot({ path: '.verify-tmp/customer-package-manager.png', fullPage: true });
  const paid = await (await request.get(`/api/companies/${company.id}/package`, { headers })).json();
  expect(paid.tenant.commercialSubscription).toMatchObject({ billingMode: 'PAID', billingCycle: 'yearly', amount: 1200 });
  expect(paid.subscription.planId).toBe(paid.tenant.selectedServicePlanIds[0]);
  expect(paid.history).toHaveLength(2);
  expect(await (await request.get('/api/invoices', { headers })).json()).toEqual(invoicesBefore);
  expect(errors).toEqual([]);
});
